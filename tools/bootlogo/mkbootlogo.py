#!/usr/bin/env python3
"""Boot logo from YOUR iOS root, for every screen before iOS draws (A, 2026-11-15).

  python3 tools/bootlogo/mkbootlogo.py [--rootfs DIR] [--up-param STOCK_UP_PARAM.img]

iPhones show one Apple logo from power-on until SpringBoard. Here three things draw before iOS: Samsung's bootloader
(up_param's logo.jpg), the UEFI, and our loader. This makes the first and the last of them show iOS's own boot logo
(ProgressUI.framework apple-logo@3x~iphone.png, the one backboardd uses), at the same physical size and place:

  xnuloader/applelogo.h   the logo's coverage, run-length coded, at the panel's native 1440 x 3200 (iOS's 3x is
                          1080 wide: x 4/3); loader.c draws it centered, white on black
  out/up_param-apple.img  the stock up_param with logo.jpg replaced (same 1440 x 3120 canvas, logo centered);
                          flash: ./x1slte.sh hlogo (Download Mode)
  out/bootlogo/           previews

The artwork is Apple's: read from the iOS root at build time, never committed (both outputs are git-ignored).
"""
import argparse
import io
import os
import struct
import subprocess
import sys
import tarfile
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import cgbi  # noqa: E402
import jpeg444  # noqa: E402

LOGO = 'System/Library/PrivateFrameworks/ProgressUI.framework/apple-logo@3x~iphone.png'
LOGO_H = 300        # one size on every screen: the UEFI's logo slot is a 300 x 300 BMP (iOS 3x 237 px x 4/3 would be 316);
                    # 300 of the panel's 3200 rows is 9.4 %, an iPhone X's 237 of 2436 is 9.7 %
UEFI_LZMA = bytes.fromhex('98584eee143959429d6edc7bd79403cf')      # EFI_LZMA_CUSTOM_DECOMPRESS_GUID
UEFI_BMP_SIZE = 91078                                                # SiliciumPkg BootLogo.bmp: 300x300, 8 bit
UEFI_HINT = b'[Volume Up] Boot Manager'      # Mu-Silicium's line under its logo (its own boot menu)
UEFI_TEXT = b'- JESVI -'                      # what it says instead (the string ends there: centered as its own length)


def find_rootfs():
    for d in (os.path.join(TOP, 'sysimage', 'rootfs'),
              os.path.join(TOP, '..', 'hackios-release-devops', 'sysimage', 'rootfs')):
        if os.path.isfile(os.path.join(d, LOGO)):
            return d
    return None


def resize(w, h, cov, nw, nh):
    """box-filtered downscale / bilinear upscale of a coverage map"""
    out = bytearray(nw * nh)
    for y in range(nh):
        fy = (y + 0.5) * h / nh - 0.5
        y0 = max(0, min(h - 1, int(fy))); y1 = min(h - 1, y0 + 1); ty = fy - y0 if fy > y0 else 0.0
        for x in range(nw):
            fx = (x + 0.5) * w / nw - 0.5
            x0 = max(0, min(w - 1, int(fx))); x1 = min(w - 1, x0 + 1); tx = fx - x0 if fx > x0 else 0.0
            a = cov[y0 * w + x0] * (1 - tx) + cov[y0 * w + x1] * tx
            b = cov[y1 * w + x0] * (1 - tx) + cov[y1 * w + x1] * tx
            out[y * nw + x] = max(0, min(255, int(round(a * (1 - ty) + b * ty))))
    return bytes(out)


def rle(cov):
    """(value, run) byte pairs, runs up to 255"""
    out, i = bytearray(), 0
    while i < len(cov):
        v, n = cov[i], 1
        while i + n < len(cov) and cov[i + n] == v and n < 255:
            n += 1
        out += bytes((v, n)); i += n
    return bytes(out)


def write_header(path, w, h, cov):
    data = rle(cov)
    with open(path, 'w') as f:
        f.write('/* GENERATED by tools/bootlogo/mkbootlogo.py from the iOS root (ProgressUI apple-logo@3x~iphone.png).\n'
                ' * Apple artwork: never commit. Coverage 0..255, (value, run) pairs, rows of APPLELOGO_W. */\n')
        f.write('#define APPLELOGO_W %d\n#define APPLELOGO_H %d\n' % (w, h))
        f.write('static const unsigned char applelogo_rle[%d] = {\n' % len(data))
        for i in range(0, len(data), 24):
            f.write('\t' + ', '.join('%d' % b for b in data[i:i + 24]) + ',\n')
        f.write('};\n')
    return len(data)


def bmp24(path, w, h, pix):
    """pix: function (x, y) -> grey 0..255; bottom-up 24-bit BMP (sips reads it)"""
    row = (w * 3 + 3) & ~3
    with open(path, 'wb') as f:
        f.write(b'BM' + struct.pack('<IHHI', 54 + row * h, 0, 0, 54))
        f.write(struct.pack('<IiiHHIIiiII', 40, w, h, 1, 24, 0, row * h, 2835, 2835, 0, 0))
        for y in range(h - 1, -1, -1):
            line = bytearray()
            for x in range(w):
                g = pix(x, y); line += bytes((g, g, g))
            f.write(line + b'\0' * (row - w * 3))


def canvas(cw, ch, w, h, cov, cy=None):
    ox, oy = (cw - w) // 2, ((ch if cy is None else 2 * cy) - h) // 2

    def pix(x, y):
        x -= ox; y -= oy
        return cov[y * w + x] if 0 <= x < w and 0 <= y < h else 0
    return pix


def to_jpeg(bmp, jpg):
    subprocess.run(['sips', '-s', 'format', 'jpeg', '-s', 'formatOptions', '95', bmp, '--out', jpg],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def make_up_param(stock, logo_jpg, out):
    src = open(stock, 'rb').read()
    tin = tarfile.open(fileobj=io.BytesIO(src))
    buf = io.BytesIO()
    tout = tarfile.open(fileobj=buf, mode='w', format=tarfile.USTAR_FORMAT)
    replaced = False
    for m in tin.getmembers():
        data = tin.extractfile(m).read() if m.isfile() else None
        if m.name == 'logo.jpg':
            data = open(logo_jpg, 'rb').read(); replaced = True
        n = tarfile.TarInfo(m.name)
        n.size = len(data) if data is not None else 0
        n.mode, n.uid, n.gid, n.uname, n.gname, n.mtime, n.type = m.mode, m.uid, m.gid, m.uname, m.gname, m.mtime, m.type
        tout.addfile(n, io.BytesIO(data) if data is not None else None)
    tout.close()
    assert replaced, 'no logo.jpg in %s' % stock
    img = buf.getvalue()
    assert len(img) <= len(src), 'new up_param (%d) larger than the partition image (%d)' % (len(img), len(src))
    open(out, 'wb').write(img + b'\0' * (len(src) - len(img)))
    return len(img)


def uefi_bmp(nw, nh, cov):
    """the UEFI's logo slot exactly as SiliciumPkg's: 300x300, 8 bit, 256 grey palette, 1078-byte offset, bottom-up"""
    W = H = 300
    pal = b''.join(bytes((g, g, g, 0)) for g in range(256))
    pix = bytearray(W * H)
    ox, oy = (W - nw) // 2, (H - nh) // 2
    for y in range(nh):
        for x in range(nw):
            pix[(H - 1 - (oy + y)) * W + ox + x] = cov[y * nw + x]
    head = b'BM' + struct.pack('<IHHI', 1078 + W * H, 0, 0, 1078) + struct.pack('<IiiHHIIiiII', 40, W, H, 1, 8, 0, W * H, 0, 0, 256, 256)
    bmp = head + pal + bytes(pix)
    assert len(bmp) == UEFI_BMP_SIZE
    return bmp


def lzma_section(d):
    """the UEFI's LZMA-compressed firmware volume: (start, end) of its data in the boot image d"""
    g = d.find(UEFI_LZMA)
    if g < 4:
        return None
    sec = g - 4
    size = int.from_bytes(d[sec:sec + 3], 'little'); doff = struct.unpack('<H', d[g + 16:g + 18])[0]
    return sec + doff, sec + size


def patch_uefi(path, bmp, hint=False, pristine=None):
    """the UEFI's logo (and its '[Volume Up] Boot Manager' line: blank unless hint) inside its LZMA-compressed firmware
    volume, every offset and size unchanged. Always made from the untouched UEFI image (pristine), so it can be redone
    either way; the result is written into the same section of path (the boot image, payload already spliced)."""
    import lzma
    d = bytearray(open(path, 'rb').read())
    src = open(pristine, 'rb').read() if pristine and os.path.isfile(pristine) else bytes(d)
    a, b = lzma_section(d) or (None, None), lzma_section(src) or (None, None)
    if a[0] is None or b[0] is None or a != b:
        return 'no LZMA section where the untouched UEFI has it: not patched'
    start, end = a
    hdr = bytes(src[start:start + 13]); props, dict_size = hdr[0], struct.unpack('<I', hdr[1:5])[0]
    raw_len = struct.unpack('<Q', hdr[5:13])[0]
    fv = bytearray(lzma.LZMADecompressor(format=lzma.FORMAT_ALONE).decompress(bytes(src[start:end])))
    assert len(fv) == raw_len
    j = fv.find(b'BM' + struct.pack('<I', UEFI_BMP_SIZE))
    if j < 0:
        return 'no %d-byte BMP in the firmware volume' % UEFI_BMP_SIZE
    assert fv[j - 28 + 19] & 0x40 == 0, 'the logo file is checksummed (FFS_ATTRIB_CHECKSUM): not patched'
    fv[j:j + UEFI_BMP_SIZE] = bmp
    k = fv.find(UEFI_HINT)
    if k >= 0 and not hint:
        fv[k:k + len(UEFI_HINT)] = UEFI_TEXT + b'\0' * (len(UEFI_HINT) - len(UEFI_TEXT))
    current = lzma.LZMADecompressor(format=lzma.FORMAT_ALONE).decompress(bytes(d[start:end]))
    if current[:raw_len] == bytes(fv):
        return 'already as wanted (iOS logo, line %s)' % ('[Volume Up] Boot Manager' if hint else UEFI_TEXT.decode())
    lc, rest = props % 9, props // 9; lp, pb = rest % 5, rest // 5
    body = lzma.compress(bytes(fv), format=lzma.FORMAT_RAW, filters=[{'id': lzma.FILTER_LZMA1, 'dict_size': dict_size,
                         'lc': lc, 'lp': lp, 'pb': pb, 'preset': 9 | lzma.PRESET_EXTREME}])
    new = hdr + body                                  # the same header: props, dictionary, the exact output size
    if len(new) > end - start:
        return 'recompressed volume %d bytes > its slot %d: not patched' % (len(new), end - start)
    check = lzma.LZMADecompressor(format=lzma.FORMAT_ALONE).decompress(new + b'\0' * (end - start - len(new)))
    assert check[:raw_len] == bytes(fv), 'round trip failed'
    d[start:end] = new + b'\0' * (end - start - len(new))
    open(path, 'wb').write(d)
    return 'patched: iOS logo, line %s (%d of %d bytes)' % ('[Volume Up] Boot Manager' if hint else UEFI_TEXT.decode(), len(new), end - start)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rootfs', default=find_rootfs())
    ap.add_argument('--up-param', default=os.path.expanduser('~/ios-port-research/device/backup/20261105-203534/up_param.img'))
    ap.add_argument('--header', default=os.path.join(TOP, 'xnuloader', 'applelogo.h'))
    ap.add_argument('--embed', default=os.path.join(TOP, 'out', 'x1slte-embed.img'),
                    help='the boot image whose UEFI logo is replaced (in place)')
    ap.add_argument('--uefi', default=os.path.expanduser('~/ios-port-research/build/uefi/Mu-x1slte.img'),
                    help='the untouched UEFI image the firmware volume is always made from')
    ap.add_argument('--dev', action='store_true', help="dev mode: keep the UEFI's '[Volume Up] Boot Manager' line")
    a = ap.parse_args()
    if not a.rootfs or not os.path.isfile(os.path.join(a.rootfs, LOGO)):
        sys.exit('mkbootlogo: no iOS root with %s (--rootfs DIR)' % LOGO)
    w, h, cov = cgbi.read(os.path.join(a.rootfs, LOGO))
    nh = LOGO_H; nw = (w * nh + h // 2) // h
    big = resize(w, h, cov, nw, nh)
    n = write_header(a.header, nw, nh, big)
    print('mkbootlogo: %s: %dx%d -> %dx%d (%d bytes RLE)' % (os.path.relpath(a.header, TOP), w, h, nw, nh, n))
    od = os.path.join(TOP, 'out', 'bootlogo'); os.makedirs(od, exist_ok=True)
    for name, ch in (('logo.jpg', 3120), ('loader-preview.jpg', 3200)):     # S-Boot centers logo.jpg on the 3200 rows
        pix = canvas(1440, ch, nw, nh, big)
        grey = bytes(pix(x, y) for y in range(ch) for x in range(1440))
        open(os.path.join(od, name), 'wb').write(jpeg444.encode(1440, ch, grey))   # baseline 4:4:4, as Samsung's
    open(os.path.join(od, 'uefi-bootlogo.bmp'), 'wb').write(uefi_bmp(nw, nh, big))
    if os.path.isfile(a.embed):
        print('mkbootlogo: UEFI logo in %s: %s' % (os.path.relpath(a.embed, TOP), patch_uefi(a.embed, uefi_bmp(nw, nh, big), a.dev, a.uefi)))
    if os.path.isfile(a.up_param):
        m = make_up_param(a.up_param, os.path.join(od, 'logo.jpg'), os.path.join(TOP, 'out', 'up_param-apple.img'))
        print('mkbootlogo: out/up_param-apple.img (tar %d bytes, logo.jpg replaced)' % m)
    else:
        print('mkbootlogo: no stock up_param at %s: out/up_param-apple.img not made' % a.up_param)


if __name__ == '__main__':
    main()
