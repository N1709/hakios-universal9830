#!/usr/bin/env python3
"""tools/kext/mksyms.py IMPORTS OUT.c: the kernel's addresses for a kext's imports, by name.

IMPORTS: one Mach-O symbol name a line (`nm -u` of the kext). OUT.c: a sorted table {name, address}; each address is
taken by an asm label, so the kernel's own link resolves it (a missing symbol fails the kernel build, not the phone).
Names only: no code of the kext goes into the source. Used by bsd/dev/redwood_kextload.c (lifs.kext).
"""
import sys

names = sorted({l.strip() for l in open(sys.argv[1]) if l.strip()})
out = ['/* generated by tools/kext/mksyms.py from tools/kext/lifs-imports.txt: do not edit */',
       '#include <stdint.h>', '#include <stddef.h>', '']
for i, n in enumerate(names):
    out.append(f'extern char rwk_s{i} __asm("{n}");')
out += ['', 'struct redwood_kextsym { const char *name; const void *addr; };',
        'const struct redwood_kextsym redwood_kextsyms[] = {']
out += [f'\t{{"{n}", &rwk_s{i}}},' for i, n in enumerate(names)]
out += ['};', f'const size_t redwood_kextsyms_count = {len(names)};', '']
open(sys.argv[2], 'w').write('\n'.join(out))
print(f'{len(names)} symbols -> {sys.argv[2]}')
