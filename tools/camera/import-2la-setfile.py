#!/usr/bin/env python3
"""Export only ordinary register settings for the verified 2LA A202 probe.
Global_1/OTP firmware payloads are deliberately excluded.
"""
import argparse
import hashlib
from pathlib import Path
import runpy
TABLE=runpy.run_path(str(Path(__file__).with_name('import-2ld-setfile.py')))['table']
NAMES=('sensor_2la_setfile_A_initial_setting','sensor_2la_setfile_A_Global_2',
       'sensor_2la_setfile_A_4032x3024_30fps','sensor_2la_dual_single_A_settings')
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('source',type=Path);p.add_argument('output',type=Path);a=p.parse_args()
 blob=a.source.read_bytes();source=blob.decode()
 lines=['/* Samsung 2LA setA ordinary registers, verified module revision A202.',
        ' * Source SHA256 '+hashlib.sha256(blob).hexdigest(),
        ' * Generated by tools/camera/import-2la-setfile.py. No Global_1 payload. */',
        '#ifndef REDWOOD_CAMERA_S20_2LA_H','#define REDWOOD_CAMERA_S20_2LA_H','#include <stdint.h>']
 for name in NAMES:
  values=TABLE(source,name);out=name.replace('sensor_','redwood_',1)
  lines.append('static const uint32_t '+out+'[]={')
  for i in range(0,len(values),9):lines.append('    '+','.join('0x%08xU'%v for v in values[i:i+9])+',')
  lines.append('};')
 lines.append('#endif');a.output.write_text('\n'.join(lines)+'\n')
if __name__=='__main__':main()
