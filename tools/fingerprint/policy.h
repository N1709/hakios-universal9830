/* Experimental biometric policy core, NOT an authenticator or unlock API.
 * No production consumer until a trusted matcher and keybag bridge exist.
 * Only a backend that has verified the secure-world result may pass
 * FP_VERIFIED_MATCH. A finger-down IRQ or client-supplied boolean is not proof.
 */
#ifndef REDWOOD_FINGERPRINT_POLICY_H
#define REDWOOD_FINGERPRINT_POLICY_H
#include <stdint.h>
#include <stdbool.h>
#include <string.h>

#define FP_REQUEST_LIFETIME 5u
#define FP_PASSCODE_LIFETIME (8u * 60u * 60u) /* conservative prototype ceiling */
/* User requested passcode fallback after an incorrect fingerprint. */
#define FP_FAILURE_LIMIT 1u

enum fp_result { FP_PRESENT, FP_NO_MATCH, FP_VERIFIED_MATCH, FP_BACKEND_ERROR };
enum fp_decision { FP_DENY, FP_WAIT, FP_ELIGIBLE_FOR_NATIVE_UNLOCK };
struct fp_policy {
    bool ready, enrolled, passcode_verified, pending;
    uint32_t failures;
    uint64_t keybag_generation, enrollment_generation, passcode_at, request_at;
    uint8_t challenge[16];
};

static void fp_policy_cancel(struct fp_policy *s) {
    s->pending=false;
    volatile uint8_t *p=s->challenge;
    for(unsigned i=0;i<sizeof(s->challenge);i++)p[i]=0;
}
static void fp_policy_require_passcode(struct fp_policy *s) {
    fp_policy_cancel(s);s->passcode_verified=false;
}
static void fp_policy_init(struct fp_policy *s) { memset(s,0,sizeof(*s)); }
static void fp_policy_backend(struct fp_policy *s,bool ready,bool enrolled,uint64_t generation) {
    if(!ready || !enrolled || !generation || generation!=s->enrollment_generation)
        fp_policy_require_passcode(s);
    s->ready=ready;s->enrolled=enrolled;s->enrollment_generation=generation;
}
/* Called ONLY following actual native passcode verification of a protected bag.
 * Never called merely because the screen/UI was dismissed or the bag unlocked. */
static bool fp_policy_passcode_verified(struct fp_policy *s,uint64_t bag,uint64_t now) {
    fp_policy_require_passcode(s);
    if(!s->ready || !s->enrolled || !s->enrollment_generation || !bag)return false;
    s->keybag_generation=bag;s->passcode_at=now;
    s->failures=0;s->passcode_verified=true;return true;
}
static bool fp_policy_eligible(struct fp_policy *s,uint64_t bag,uint64_t now) {
    if(!s->ready || !s->enrolled || !s->passcode_verified || !bag ||
        bag!=s->keybag_generation || now<s->passcode_at ||
        now-s->passcode_at>=FP_PASSCODE_LIFETIME || s->failures>=FP_FAILURE_LIMIT) {
        fp_policy_require_passcode(s);return false;
    }
    return true;
}
/* Challenge must be freshly generated by the trusted coordinator's CSPRNG.
 * Screen-off, cancel, user switch and enrollment change cancel this request. */
static bool fp_policy_begin(struct fp_policy *s,uint64_t bag,uint64_t now,const uint8_t challenge[16]) {
    fp_policy_cancel(s);
    if(!challenge || !fp_policy_eligible(s,bag,now))return false;
    unsigned nonzero=0;for(unsigned i=0;i<16;i++)nonzero|=challenge[i];
    if(!nonzero)return false;
    memcpy(s->challenge,challenge,16);s->request_at=now;s->pending=true;return true;
}
static enum fp_decision fp_policy_result(struct fp_policy *s,uint64_t bag,uint64_t enrollment,
    uint64_t now,const uint8_t challenge[16],enum fp_result result) {
    if(!fp_policy_eligible(s,bag,now) || !s->pending || !challenge)return FP_DENY;
    unsigned different=0;for(unsigned i=0;i<16;i++)different|=s->challenge[i]^challenge[i];
    if(different || enrollment!=s->enrollment_generation || now<s->request_at ||
        now-s->request_at>=FP_REQUEST_LIFETIME) {
        fp_policy_require_passcode(s);return FP_DENY;
    }
    if(result==FP_PRESENT)return FP_WAIT; /* presence never authenticates */
    fp_policy_cancel(s); /* each completed result is single-use */
    if(result==FP_VERIFIED_MATCH)return FP_ELIGIBLE_FOR_NATIVE_UNLOCK;
    if(result==FP_NO_MATCH && s->failures<UINT32_MAX)s->failures++;
    fp_policy_require_passcode(s);return FP_DENY;
}
#endif
