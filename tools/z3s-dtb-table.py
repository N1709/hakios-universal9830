#!/usr/bin/env python3
"""Wrap the raw z3s FDT in the Samsung DT table that sboot expects.

Samsung's bootloader rejects a raw FDT in an Android v2 boot image's DTB
section with:

  DTB DT TABLE HEADER CHECK FAIL: FDT_ERR_BADMAGIC
  UFDT DTB LOAD FAIL

The stock G988BXXUBDUI5 boot image carries a 0x40-byte table (magic
`d7b7ab1e`) around the same FDT. x1slte hit the identical failure on
2026-11-05; `x1slte.sh` uses the stock table and sets `dtb_addr` to
0x10000000.

The z3s stock table (342,016 bytes) is exactly this layout around the
committed `z3s.dtb`; `--check` proves the generated bytes match it.

usage:
  tools/z3s-dtb-table.py --fdt z3s.dtb --out z3s-dtb-table.img
  tools/z3s-dtb-table.py --fdt z3s.dtb --check stock-boot-dtb.img
"""
import argparse
import struct
import sys
from pathlib import Path

MAGIC = 0xd7B7AB1E
HEADER = 0x40
ALIGN = 0x800
DTB_ADDR = 0x10000000


def wrap(fdt):
    """Return the Samsung DT table around one raw FDT."""
    if fdt[:4] != b"\xd0\x0d\xfe\xed":
        raise ValueError("input is not a raw FDT (no d00dfeed magic)")
    if len(fdt) < HEADER:
        raise ValueError("FDT is shorter than the table header")
    total = HEADER + len(fdt)
    h = bytearray(HEADER)
    struct.pack_into(">I", h, 0x00, MAGIC)
    struct.pack_into(">I", h, 0x04, total)      # table size, unpadded
    struct.pack_into(">I", h, 0x08, 0x20)
    struct.pack_into(">I", h, 0x0C, 0x20)
    struct.pack_into(">I", h, 0x10, 1)          # one entry
    struct.pack_into(">I", h, 0x14, 0x20)
    struct.pack_into(">I", h, 0x18, ALIGN)
    struct.pack_into(">I", h, 0x1C, 0)
    struct.pack_into(">I", h, 0x20, len(fdt))   # FDT size
    struct.pack_into(">I", h, 0x24, HEADER)     # FDT offset
    struct.pack_into(">I", h, 0x28, 0)
    struct.pack_into(">I", h, 0x2C, 0)
    struct.pack_into(">I", h, 0x30, 0)
    struct.pack_into(">I", h, 0x34, 0xFF000000)
    struct.pack_into(">I", h, 0x38, 0)
    struct.pack_into(">I", h, 0x3C, 0)
    table = bytes(h) + fdt
    return table + b"\0" * (-len(table) % ALIGN)


def check(table):
    """Reject a table that is not the one-entry Samsung layout."""
    if len(table) < HEADER or struct.unpack_from(">I", table, 0)[0] != MAGIC:
        raise ValueError("not a Samsung DT table (no d7b7ab1e magic)")
    total, count, fdt_size, fdt_at = (
        struct.unpack_from(">I", table, at)[0] for at in (0x04, 0x10, 0x20, 0x24)
    )
    if count != 1 or fdt_at != HEADER or total != HEADER + fdt_size:
        raise ValueError(f"unexpected table geometry: total={total:#x} count={count} "
                         f"fdt={fdt_size:#x}@{fdt_at:#x}")
    if fdt_at + fdt_size > len(table):
        raise ValueError("FDT runs past the table")
    if table[fdt_at:fdt_at + 4] != b"\xd0\x0d\xfe\xed":
        raise ValueError("table entry is not a raw FDT")
    if len(table) % ALIGN:
        raise ValueError(f"table length {len(table)} is not {ALIGN:#x}-aligned")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--fdt", required=True, help="raw FDT (z3s.dtb)")
    ap.add_argument("--out", help="write the Samsung DT table here")
    ap.add_argument("--check", help="compare the generated table with a stock table")
    args = ap.parse_args()

    fdt = Path(args.fdt).read_bytes()
    table = wrap(fdt)
    check(table)
    print(f"DT table: {len(table)} bytes, magic d7b7ab1e, FDT {len(fdt)} bytes at 0x40")

    if args.check:
        stock = Path(args.check).read_bytes()
        if table != stock:
            for i, (a, b) in enumerate(zip(table, stock)):
                if a != b:
                    raise SystemExit(f"differs from {args.check} at 0x{i:x}: {a:#x} != {b:#x}")
            raise SystemExit(f"length differs from {args.check}: {len(table)} != {len(stock)}")
        print(f"matches the stock table {args.check} byte for byte")

    if args.out:
        Path(args.out).write_bytes(table)
        print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
