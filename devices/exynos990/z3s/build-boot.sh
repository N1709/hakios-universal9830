#!/bin/bash
# Pack the z3s UEFI FD, loader.efi and the prebuilt XNU kernel into an Android
# boot image. Run this on the laptop or in CI, never on the phone.
#
#   ./devices/exynos990/z3s/build-boot.sh /path/to/SILICIUM_UEFI.fd [outdir]
#
# The image has two XNUP payloads:
#   FD + 0x100000  loader.efi only, for the UEFI XnuLoader hook (1 MiB slot)
#   0xF0000000     kernel + cmdline, copied there by the boot shim (15 MiB slot)
#
# Build the loader for the second window first:
#   PAYLOAD_BASE=0xF0000000 PAYLOAD_MAX_SIZE=0x00F00000 PANIC_LOG_BASE=0xF0F00000 \
#       ./xnuloader/build.sh
#
# The boot shim and mkbootimg come from the Mu-Silicium tree when MU is set;
# otherwise pass SHIM=, MKBOOTIMG= and RAMDISK= explicitly. The output is the
# sparse image, full-size recovery.img and boot.img (AVB hash footer, padded to
# their PIT partitions), and an Odin AP tar with recovery.img and its .md5,
# because the z3s chain (like x1slte) starts from the recovery partition.
set -euo pipefail
cd "$(dirname "$0")/../../.."

FD=${1:?usage: $0 <SILICIUM_UEFI.fd> [outdir]}
OUT=${2:-out/z3s-boot}
LOADER=${LOADER:-xnuloader/loader.efi}
KERNEL=${KERNEL:-prebuilt/mach.development.bcm2837}
DTB=${DTB:-devices/exynos990/z3s/uefi-z3s/Resources/DTBs/z3s.dtb}
DTB_TABLE=${DTB_TABLE:-$OUT/z3s-dtb-table.img}
CMDLINE_FILE=${CMDLINE_FILE:-devices/exynos990/z3s/z3s.cmdline}
IMAGE=z3s-recovery.img
# PIT recovery/boot partitions (G988BXXUBDUI5, PICASSO3_EUR_OPEN.pit). AVB
# pads the flashed image to this size so Odin writes the whole slot and the
# loader's log area at recovery+16 MiB starts zeroed. The sparse image stays
# as the verifier input and for quick size checks.
RECOVERY_SIZE=${RECOVERY_SIZE:-69009408}
BOOT_SIZE=${BOOT_SIZE:-61865984}

die() { echo "build-boot.sh: $*" >&2; exit 1; }
[ -f "$FD" ] || die "no FD at $FD"
[ -f "$LOADER" ] || die "no loader at $LOADER (build xnuloader/build.sh first)"
[ -f "$KERNEL" ] || die "no kernel at $KERNEL"
[ -f "$DTB" ] || die "no DTB at $DTB"
[ -f "$CMDLINE_FILE" ] || die "no cmdline at $CMDLINE_FILE"
python3 - "$FD" <<'PY'
import sys
from pathlib import Path
fd = Path(sys.argv[1]).read_bytes()
if len(fd) != 0x200000:
    raise SystemExit(f"FD is {len(fd):#x} bytes, expected 0x200000")
if fd[0x28:0x2c] != b"_FVH":
    raise SystemExit("FD has no _FVH at 0x28")
if fd[0x100000:0x100004] != b"\xff\xff\xff\xff":
    print("build-boot.sh: warning: the FD tail is not erased; it will be replaced")
PY

mkdir -p "$OUT"
CMDLINE=$(tr '\n' ' ' < "$CMDLINE_FILE" | sed 's/[[:space:]]*$//')
[ -n "$CMDLINE" ] || die "the cmdline file is empty"

# sboot rejects a raw FDT in the boot image's DTB section with
# "DTB DT TABLE HEADER CHECK FAIL: FDT_ERR_BADMAGIC". The stock z3s boot.img
# carries the same FDT inside a Samsung DT table (magic d7b7ab1e); the
# generated bytes match that stock table exactly.
python3 tools/z3s-dtb-table.py --fdt "$DTB" --out "$DTB_TABLE"
[ -f "$DTB_TABLE" ] || die "no DT table at $DTB_TABLE"

python3 xnuloader/mkpayload.py -o "$OUT/fd-payload.bin" loader.efi="$LOADER"
python3 xnuloader/mkpayload.py -o "$OUT/kernel-payload.bin" kernel="$KERNEL" --cmdline="$CMDLINE"

# The shim and mkbootimg come from the Mu-Silicium tree when it is present;
# otherwise pass SHIM=, MKBOOTIMG= and RAMDISK= explicitly.
if [ -n "${MU:-}" ]; then
	export SHIM=${SHIM:-$MU/BootShim/BootShim.bin}
	export MKBOOTIMG=${MKBOOTIMG:-$MU/Resources/Scripts/mkbootimg.py}
	export RAMDISK=${RAMDISK:-$MU/Resources/ramdisk}
fi
[ -n "${SHIM:-}" ] || die "set MU=... or SHIM=/path/to/BootShim.bin"
[ -n "${MKBOOTIMG:-}" ] || die "set MU=... or MKBOOTIMG=/path/to/mkbootimg.py"
[ -n "${RAMDISK:-}" ] || die "set MU=... or RAMDISK=/path/to/ramdisk"
[ -f "$SHIM" ] || die "no boot shim at $SHIM"
[ -f "$MKBOOTIMG" ] || die "no mkbootimg at $MKBOOTIMG"
[ -f "$RAMDISK" ] || die "no ramdisk at $RAMDISK"

UEFI_FD="$FD" DTB="$DTB_TABLE" FD_BASE=0xE8000000 FD_SIZE=0x200000 \
	PAYLOAD_BASE=0xF0000000 FD_PAYLOAD_AT=0x100000 HEADER_VERSION=2 \
	python3 xnu/mkxnuimg.py --fd-payload "$OUT/fd-payload.bin" \
		-p "$OUT/kernel-payload.bin" -o "$OUT/$IMAGE"

# mkbootimg writes dtb_addr as base+dtb_offset (0x11f00000); the stock z3s
# boot.img and TWRP use 0x10000000. The header id is already the SHA-1 of the
# DT table, and this address is outside that hash.
python3 - "$OUT/$IMAGE" "$DTB_TABLE" <<'PY'
import struct, sys
from pathlib import Path
image, table = Path(sys.argv[1]), Path(sys.argv[2])
d = bytearray(image.read_bytes())
if d[:8] != b"ANDROID!" or struct.unpack_from("<I", d, 40)[0] != 2:
    raise SystemExit("not an Android v2 boot image")
ps = struct.unpack_from("<I", d, 36)[0]
pg = lambda n: (n + ps - 1) // ps * ps
ks, rs, ss = (struct.unpack_from("<I", d, o)[0] for o in (8, 16, 24))
rec = struct.unpack_from("<I", d, 1632)[0]
doff = ps + pg(ks) + pg(rs) + pg(ss) + pg(rec)
dsz = struct.unpack_from("<I", d, 1648)[0]
want = table.read_bytes()
if d[doff:doff + 4] != b"\xd7\xb7\xab\x1e":
    raise SystemExit(f"no Samsung DT table at {doff:#x}: {d[doff:doff + 4].hex()}")
if dsz != len(want) or d[doff:doff + dsz] != want:
    raise SystemExit(f"DTB section {dsz} bytes does not match the table ({len(want)})")
struct.pack_into("<Q", d, 1652, 0x10000000)
image.write_bytes(d)
print(f"dtb: Samsung table {dsz} bytes at {doff:#x}, dtb_addr 0x10000000")
PY

python3 tools/z3s-boot-verify.py --image "$OUT/$IMAGE" \
	--shim "$SHIM" --loader "$LOADER" --kernel "$KERNEL"

# An AVB hash footer, as TWRP's recovery has: z3s's sboot (like x1slte's)
# drops to Download Mode without one, even with vbmeta verification off
# (x1slte, 2026-11-05). add_hash_footer pads the image to the measured PIT
# partition and hashes only the boot image head (shim + UEFI + payload).
# The loader's log window at recovery+16 MiB is outside that hash, so a
# later boot still verifies after the loader has written its log.
AVBTOOL=${AVBTOOL:-inputs/tools/avbtool.py}
AVB_TEST_KEY=${AVB_TEST_KEY:-inputs/tools/testkey_rsa4096.pem}
if [ ! -f "$AVBTOOL" ] || [ ! -f "$AVB_TEST_KEY" ]; then
	tools/get-avb.sh inputs/tools
fi
[ -f "$AVBTOOL" ] || die "no avbtool at $AVBTOOL"
[ -f "$AVB_TEST_KEY" ] || die "no AVB test key at $AVB_TEST_KEY"

cp "$OUT/$IMAGE" "$OUT/recovery.img"
cp "$OUT/$IMAGE" "$OUT/boot.img"
python3 -I "$AVBTOOL" add_hash_footer --image "$OUT/recovery.img" \
	--partition_size "$RECOVERY_SIZE" --partition_name recovery \
	--algorithm SHA256_RSA4096 --key "$AVB_TEST_KEY" --rollback_index 1
python3 -I "$AVBTOOL" add_hash_footer --image "$OUT/boot.img" \
	--partition_size "$BOOT_SIZE" --partition_name boot \
	--algorithm SHA256_RSA4096 --key "$AVB_TEST_KEY" --rollback_index 1
python3 - "$OUT/recovery.img" "$OUT/boot.img" <<'PY'
import struct, sys
from pathlib import Path
for name in sys.argv[1:]:
    path = Path(name)
    data = path.read_bytes()
    footer = data[-64:]
    if footer[:4] != b"AVBf":
        raise SystemExit(f"{path.name}: no AVB footer at the end")
    head = struct.unpack_from(">Q", footer, 12)[0]
    if head >= 0x1000000:
        raise SystemExit(f"{path.name}: AVB head {head:#x} reaches the log window at 0x1000000")
    print(f"{path.name}: AVB footer, hashed head {head} bytes, {len(data)} bytes total")
PY
python3 -I "$AVBTOOL" info_image --image "$OUT/recovery.img" |
	sed -n '1,4p;/Algorithm/p;/Partition Name/p'
tar -C "$OUT" --mtime=@0 --owner=0 --group=0 --numeric-owner \
	-cf "$OUT/z3s-recovery.tar" recovery.img
cp "$OUT/z3s-recovery.tar" "$OUT/z3s-recovery.tar.md5"
md5sum "$OUT/z3s-recovery.tar" | cut -d' ' -f1 | tr -d '\n' >> "$OUT/z3s-recovery.tar.md5"
echo >> "$OUT/z3s-recovery.tar.md5"

SHIM_ABS=$(realpath "$SHIM")
LOADER_ABS=$(realpath "$LOADER")
KERNEL_ABS=$(realpath "$KERNEL")
AVB_KEY_ABS=$(realpath "$AVB_TEST_KEY")
(
	cd "$OUT"
	sha256sum "$IMAGE" recovery.img boot.img z3s-recovery.tar z3s-recovery.tar.md5 \
		fd-payload.bin kernel-payload.bin > SHA256SUMS
	python3 - "$IMAGE" "$SHIM_ABS" "$LOADER_ABS" "$KERNEL_ABS" "$RECOVERY_SIZE" "$BOOT_SIZE" "$AVB_KEY_ABS" <<'PY'
import hashlib, json, struct, sys
from pathlib import Path

def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def avb_head(path):
    footer = Path(path).read_bytes()[-64:]
    if footer[:4] != b"AVBf":
        raise SystemExit(f"{path}: no AVB footer")
    return struct.unpack_from(">Q", footer, 12)[0]

image, shim, loader, kernel, recovery_size, boot_size, avb_key = sys.argv[1:]
print(json.dumps({
    "device": "z3s",
    "image": image,
    "image_bytes": Path(image).stat().st_size,
    "image_sha256": digest(image),
    "recovery_img": "recovery.img",
    "recovery_img_bytes": Path("recovery.img").stat().st_size,
    "recovery_img_sha256": digest("recovery.img"),
    "recovery_partition_bytes": int(recovery_size),
    "boot_img": "boot.img",
    "boot_img_bytes": Path("boot.img").stat().st_size,
    "boot_img_sha256": digest("boot.img"),
    "boot_partition_bytes": int(boot_size),
    "avb_algorithm": "SHA256_RSA4096",
    "avb_key_sha256": digest(avb_key),
    "recovery_avb_hashed_head": avb_head("recovery.img"),
    "boot_avb_hashed_head": avb_head("boot.img"),
    "odin_tar": "z3s-recovery.tar",
    "odin_tar_md5": Path("z3s-recovery.tar.md5").read_bytes()[-33:-1].decode("ascii"),
    "log_partition": "recovery",
    "log_offset": "0x1000000",
    "log_length": "0x800000",
    "shim_sha256": digest(shim),
    "loader_sha256": digest(loader),
    "kernel_sha256": digest(kernel),
    "fd_payload_at": "0x100000",
    "kernel_payload_base": "0xF0000000",
    "kernel_payload_max": "0x00F00000",
    "hardware_tested": False,
    "installer_validated": False,
}, indent=2) + "\n", end="")
PY
) > "$OUT/build.json"

echo "build-boot.sh: $OUT/$IMAGE"
echo "build-boot.sh: $OUT/recovery.img ($RECOVERY_SIZE bytes)"
echo "build-boot.sh: $OUT/z3s-recovery.tar.md5"
